using System.Data;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Data.SqlClient;
using QMS.Importer;

// QMS SharePoint CSV -> SQL Server importer.
//
//   schema <csvDir> <outFile>          Infer table definitions from the CSV exports and write a CREATE script.
//   import <csvDir> <sqlDir> <conn>    (Re)create the database objects from every *.sql in sqlDir, then bulk-load all CSVs.

if (args.Length < 3)
{
    Console.WriteLine("Usage:\n  schema <csvDir> <outFile>\n  import <csvDir> <sqlDir> <connectionString>");
    return 1;
}

var csvDir = args[1];
var files = Directory.GetFiles(csvDir, "*.csv").OrderBy(f => f, StringComparer.OrdinalIgnoreCase).ToList();

switch (args[0])
{
    case "schema":
        File.WriteAllText(args[2], GenerateSchema(files), Encoding.UTF8);
        Console.WriteLine($"Wrote schema for {files.Count} lists to {args[2]}");
        return 0;

    case "import":
        if (args.Length < 4) { Console.WriteLine("import needs <csvDir> <sqlDir> <connectionString>"); return 1; }
        await Import(files, args[2], args[3]);
        return 0;

    default:
        Console.WriteLine($"Unknown command '{args[0]}'");
        return 1;
}

static string GenerateSchema(List<string> files)
{
    var sb = new StringBuilder();
    sb.AppendLine("-- Generated by QMS.Importer from the SharePoint list CSV exports. One table per list.");
    sb.AppendLine("-- Column names are sanitised; dbo._ColumnMap records the original SharePoint column for each.");
    sb.AppendLine();
    sb.AppendLine("IF OBJECT_ID('dbo._ColumnMap') IS NOT NULL DROP TABLE dbo._ColumnMap;");
    sb.AppendLine("CREATE TABLE dbo._ColumnMap (TableName sysname NOT NULL, ColumnName sysname NOT NULL, SourceList nvarchar(255) NOT NULL, SourceColumn nvarchar(400) NOT NULL, PRIMARY KEY (TableName, ColumnName));");
    sb.AppendLine("GO");

    var map = new StringBuilder();
    foreach (var file in files)
    {
        var list = Path.GetFileNameWithoutExtension(file);
        var table = Naming.Table(list);
        var rows = Csv.ReadAll(file);
        var headers = rows[0];
        var columns = UniqueColumns(headers);

        sb.AppendLine();
        sb.AppendLine($"-- {list}  ({rows.Count - 1} rows)");
        sb.AppendLine($"IF OBJECT_ID('dbo.[{table}]') IS NOT NULL DROP TABLE dbo.[{table}];");
        sb.AppendLine($"CREATE TABLE dbo.[{table}] (");

        var defs = new List<string>();
        var hasId = columns.Contains("ID");
        if (!hasId) defs.Add("    [ID] int IDENTITY(1,1) NOT NULL PRIMARY KEY");

        for (var c = 0; c < headers.Length; c++)
        {
            var type = Values.InferSqlType(headers[c], rows.Skip(1).Select(r => c < r.Length ? r[c] : ""));
            defs.Add(columns[c] == "ID"
                ? "    [ID] int IDENTITY(1,1) NOT NULL PRIMARY KEY"
                : $"    [{columns[c]}] {type} NULL");
            map.AppendLine($"INSERT dbo._ColumnMap VALUES (N'{table}', N'{columns[c]}', N'{Esc(list)}', N'{Esc(headers[c])}');");
        }
        sb.AppendLine(string.Join(",\n", defs));
        sb.AppendLine(");");

        foreach (var fk in columns.Where(c => c is "ID_Master" or "ID_Client" or "ClientID" || (c.StartsWith("ID_") && c != "ID_Master")))
            sb.AppendLine($"CREATE INDEX [IX_{table}_{fk}] ON dbo.[{table}] ([{fk}]);");
        sb.AppendLine("GO");
    }

    sb.AppendLine();
    sb.Append(map);
    sb.AppendLine("GO");
    return sb.ToString();
}

static async Task Import(List<string> files, string sqlDir, string connectionString)
{
    var csb = new SqlConnectionStringBuilder(connectionString);
    var database = csb.InitialCatalog;
    csb.InitialCatalog = "master";
    await using (var master = new SqlConnection(csb.ConnectionString))
    {
        await master.OpenAsync();
        await using var cmd = new SqlCommand($"IF DB_ID(N'{database}') IS NULL CREATE DATABASE [{database}]", master);
        await cmd.ExecuteNonQueryAsync();
    }

    await using var conn = new SqlConnection(connectionString);
    await conn.OpenAsync();

    // *.post.sql scripts run after the data load (they seed from imported data); all others run before it.
    var scripts = Directory.GetFiles(sqlDir, "*.sql").OrderBy(f => f, StringComparer.OrdinalIgnoreCase).ToList();
    var postScripts = scripts.Where(s => s.EndsWith(".post.sql", StringComparison.OrdinalIgnoreCase)).ToList();
    foreach (var script in scripts.Except(postScripts)) await RunScript(conn, script);

    var totalRows = 0;
    foreach (var file in files)
    {
        var list = Path.GetFileNameWithoutExtension(file);
        var table = Naming.Table(list);
        var rows = Csv.ReadAll(file);
        var columns = UniqueColumns(rows[0]);

        var types = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        await using (var cmd = new SqlCommand(
            "SELECT c.name, TYPE_NAME(c.user_type_id) FROM sys.columns c WHERE c.object_id = OBJECT_ID(@t)", conn))
        {
            cmd.Parameters.AddWithValue("@t", "dbo." + table);
            await using var r = await cmd.ExecuteReaderAsync();
            while (await r.ReadAsync()) types[r.GetString(0)] = r.GetString(1);
        }
        if (types.Count == 0) { Console.WriteLine($"  SKIP {list}: table dbo.{table} not found"); continue; }

        var dt = new DataTable();
        var targets = new List<(int csvIndex, string column, string type)>();
        for (var c = 0; c < columns.Length; c++)
        {
            if (!types.TryGetValue(columns[c], out var type)) continue;
            targets.Add((c, columns[c], type));
            dt.Columns.Add(columns[c], typeof(object));
        }

        var failures = new Dictionary<string, int>();
        foreach (var row in rows.Skip(1))
        {
            var values = new object[targets.Count];
            for (var i = 0; i < targets.Count; i++)
            {
                var (idx, column, type) = targets[i];
                values[i] = Values.Convert(idx < row.Length ? row[idx] : null, type, out var failed);
                if (failed) failures[column] = failures.GetValueOrDefault(column) + 1;
            }
            dt.Rows.Add(values);
        }

        using (var bulk = new SqlBulkCopy(conn, SqlBulkCopyOptions.KeepIdentity | SqlBulkCopyOptions.TableLock, null)
               { DestinationTableName = $"dbo.[{table}]", BulkCopyTimeout = 600, BatchSize = 2000 })
        {
            foreach (DataColumn col in dt.Columns) bulk.ColumnMappings.Add(col.ColumnName, col.ColumnName);
            await bulk.WriteToServerAsync(dt);
        }

        totalRows += dt.Rows.Count;
        Console.WriteLine($"  {table,-32} {dt.Rows.Count,6} rows" +
            (failures.Count > 0 ? "   (unparsed -> NULL: " + string.Join(", ", failures.Select(f => $"{f.Key}={f.Value}")) + ")" : ""));
    }

    foreach (var script in postScripts) await RunScript(conn, script);
    Console.WriteLine($"Imported {totalRows} rows from {files.Count} lists into {database}.");
}

static async Task RunScript(SqlConnection conn, string script)
{
    Console.WriteLine($"Running {Path.GetFileName(script)}");
    foreach (var batch in Regex.Split(File.ReadAllText(script), @"^\s*GO\s*$", RegexOptions.Multiline | RegexOptions.IgnoreCase))
    {
        if (string.IsNullOrWhiteSpace(batch)) continue;
        await using var cmd = new SqlCommand(batch, conn) { CommandTimeout = 300 };
        await cmd.ExecuteNonQueryAsync();
    }
}

static string[] UniqueColumns(string[] headers)
{
    var seen = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
    return headers.Select(h =>
    {
        var name = Naming.Column(h);
        var n = seen.GetValueOrDefault(name) + 1;
        seen[name] = n;
        return n == 1 ? name : name + n;
    }).ToArray();
}

static string Esc(string s) => s.Replace("'", "''");
